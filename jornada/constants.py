"""Protocol constants for the Windows CE 2.x ActiveSync/RAPI wire protocols."""
from __future__ import annotations

# --- Network layout (matches SynCE defaults) --------------------------------
DEFAULT_LOCAL_IP = "192.168.131.102"   # the Mac's end of the PPP link
DEFAULT_REMOTE_IP = "192.168.131.201"  # the Jornada's end of the PPP link
DEFAULT_BAUD = 19200                   # Jornada "PC Connection" default rate

# --- dccm: the "desktop" side of an ActiveSync connection -------------------
DCCM_PORT = 5679
DCCM_PING = 0x12345678
DCCM_PING_INTERVAL_S = 5.0
DCCM_MAX_MISSED_PINGS = 3
DCCM_MAX_PACKET_SIZE = 512
DCCM_MIN_PACKET_SIZE = 0x24

# --- RAPI: remote API served by the device ---------------------------------
RAPI_PORT = 990
RAPI_RECV_TIMEOUT_S = 30.0

# RAPI command codes (librapi2 0.9.x, "old" protocol used by CE 2.x/3.x)
CMD_FIND_FIRST_FILE = 0x00
CMD_FIND_NEXT_FILE = 0x01
CMD_FIND_CLOSE = 0x02
CMD_GET_FILE_ATTRIBUTES = 0x03
CMD_SET_FILE_ATTRIBUTES = 0x04
CMD_CREATE_FILE = 0x05
CMD_READ_FILE = 0x06
CMD_WRITE_FILE = 0x07
CMD_CLOSE_HANDLE = 0x08
CMD_FIND_ALL_FILES = 0x09
CMD_CREATE_DIRECTORY = 0x17
CMD_REMOVE_DIRECTORY = 0x18
CMD_CREATE_PROCESS = 0x19
CMD_MOVE_FILE = 0x1A
CMD_COPY_FILE = 0x1B
CMD_DELETE_FILE = 0x1C
CMD_GET_FILE_SIZE = 0x1D
CMD_GET_STORE_INFORMATION = 0x29
CMD_GET_SYSTEM_INFO = 0x2F
CMD_GET_VERSION_EX = 0x3B
CMD_GET_SYSTEM_POWER_STATUS_EX = 0x41
CMD_GET_SPECIAL_FOLDER_PATH = 0x44

# CeFindAllFiles flags
FAF_ATTRIBUTES = 0x0001
FAF_CREATION_TIME = 0x0002
FAF_LASTACCESS_TIME = 0x0004
FAF_LASTWRITE_TIME = 0x0008
FAF_SIZE_HIGH = 0x0010
FAF_SIZE_LOW = 0x0020
FAF_OID = 0x0040
FAF_NAME = 0x0080
FAF_ATTRIB_CHILDREN = 0x1000
FAF_ATTRIB_NO_HIDDEN = 0x2000
FAF_FOLDERS_ONLY = 0x4000
FAF_NO_HIDDEN_SYS_ROMMODULES = 0x8000
FAF_LISTING = FAF_ATTRIBUTES | FAF_LASTWRITE_TIME | FAF_SIZE_LOW | FAF_SIZE_HIGH | FAF_NAME

# File attributes
FILE_ATTRIBUTE_READONLY = 0x0001
FILE_ATTRIBUTE_HIDDEN = 0x0002
FILE_ATTRIBUTE_SYSTEM = 0x0004
FILE_ATTRIBUTE_DIRECTORY = 0x0010
FILE_ATTRIBUTE_ARCHIVE = 0x0020
FILE_ATTRIBUTE_INROM = 0x0040
FILE_ATTRIBUTE_NORMAL = 0x0080
FILE_ATTRIBUTE_ROMMODULE = 0x2000
INVALID_FILE_ATTRIBUTES = 0xFFFFFFFF

# CeCreateFile parameters
GENERIC_READ = 0x80000000
GENERIC_WRITE = 0x40000000
FILE_SHARE_READ = 0x00000001
CREATE_NEW = 1
CREATE_ALWAYS = 2
OPEN_EXISTING = 3
OPEN_ALWAYS = 4
TRUNCATE_EXISTING = 5
INVALID_HANDLE_VALUE = 0xFFFFFFFF

# Transfer chunking: 19200 baud is ~1.9 KB/s, keep chunks small for progress
# and to stay well inside the device's reply window.
READ_CHUNK = 8 * 1024
WRITE_CHUNK = 8 * 1024

# Sizes of fixed structs returned by misc commands
SIZEOF_STORE_INFORMATION = 8
SIZEOF_SYSTEM_POWER_STATUS_EX = 24
SIZEOF_PROCESS_INFORMATION = 16

# Win32 epoch (1601-01-01) to Unix epoch offset, in 100ns ticks
FILETIME_EPOCH_DELTA = 116444736000000000
